#!/bin/sh
# Static x86-64 crun 1.30.1 + containers/crun#2402, built with crun's own Nix flake the way
# build-aux/release.sh does. Runs in docker.io/nixos/nix. Writes the binary and SHA256SUMS to $1.
set -eux
OUT=${1:-/out}
HERE=$(cd "$(dirname "$0")" && pwd)
TAG=1.30.1
NAME=crun-$TAG-enoent-linux-amd64

rm -rf "$OUT"/* /work && mkdir -p "$OUT"
git clone --branch "$TAG" --recurse-submodules https://github.com/containers/crun /work
cd /work
# Fixed identity and dates, so the patched commit (shown by `crun --version`) is the same every build.
GIT_COMMITTER_NAME=buildio-contribs GIT_COMMITTER_EMAIL=contribs@build.io \
  git am --committer-date-is-author-date "$HERE"/patches/*.patch
printf '/* autogenerated.  */\n#ifndef GIT_VERSION\n# define GIT_VERSION "%s"\n#endif\n' "$(git rev-parse HEAD)" > .tarball-git-version.h

nix --extra-experimental-features "nix-command flakes" --option sandbox false --option filter-syscalls false \
  --print-build-logs --option cores "$(nproc)" --option max-jobs auto build "path:.#crun-static-amd64"
install -m 0755 result/bin/crun "$OUT/$NAME"
"$OUT/$NAME" --version
cd "$OUT" && sha256sum "$NAME" > SHA256SUMS
